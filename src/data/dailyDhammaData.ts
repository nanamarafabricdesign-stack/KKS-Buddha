export function getDailyQuoteForDate(date: Date = new Date(), category: 'all' | 'sutta' | 'jataka' | 'abhidhamma' = 'all'): DailyQuote {
  const filtered = category === 'all'
    ? dailyQuotes
    : dailyQuotes.filter((q) => q.category === category);
  const pool = filtered.length > 0 ? filtered : dailyQuotes;
  const dayIndex = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return pool[Math.abs(dayIndex) % pool.length];
}
